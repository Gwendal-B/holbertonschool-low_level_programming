#include "3-calc.h"

/**
* op_add - addition
* @a: entier 1
* @b: entier 2
* Return: Resultat
*/
int op_add(int a, int b)
{
	return (a + b);
}
/**
* op_sub - soustraction
* @a: entier 1
* @b: entier 2
* Return: Resultat
*/
int op_sub(int a, int b)
{
	return (a - b);
}
/**
* op_mul - multiplication
* @a: entier 1
* @b: entier 2
* Return: Resultat
*/
int op_mul(int a, int b)
{
	return (a * b);
}
/**
* op_div - division
* @a: entier 1
* @b: entier 2
* Return: Resultat
*/
int op_div(int a, int b)
{
	return (a / b);
}
/**
* op_mod - modulo
* @a: entier 1
* @b: entier 2
* Return: Resultat
*/
int op_mod(int a, int b)
{
	return (a % b);
}
